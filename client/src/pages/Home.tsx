import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';

export default function Home() {
  const [provider, setProvider] = useState<string>('');
  useEffect(() => {
    fetch('/api/config')
      .then((r) => r.json())
      .then((r) => setProvider(r.provider));
  }, []);
  return (
    <div className="home">
      <div className="home-bg">
        {Array.from({ length: 18 }).map((_, i) => (
          <span key={i} className="floaty" style={{ left: `${(i * 53) % 100}%`, animationDelay: `${-i * 1.7}s`, animationDuration: `${14 + (i % 5) * 3}s` }} />
        ))}
      </div>
      <main className="home-main">
        <div className="logo huge">
          Guess<span>the</span>Mesh
        </div>
        <h1 className="title">
          3D Pictionary where <span className="hl">AI does the sculpting.</span>
        </h1>
        <p className="lede">
          Whisper a prompt from your phone. Lux3D turns it into a 3D model. Everyone else watches it emerge — voxels, then clay, then full colour — and races to guess what
          it is.
        </p>
        <div className="home-actions">
          <Link to="/host" className="button primary huge">
            📺 Host a party game
          </Link>
          <Link to="/play" className="button secondary huge">
            📱 Join with a code
          </Link>
          <Link to="/solo" className="button ghost huge">
            🧊 Daily Mesh (solo)
          </Link>
          <Link to="/gallery" className="button ghost huge">
            🖼 Gallery
          </Link>
        </div>
        <div className="muted small">
          {provider === 'lux3d' ? 'Live: models generated by Manycore Lux3D text-to-3D.' : provider === 'mock' ? 'Running in mock mode with sample models (set AHOLO_API_KEY for live Lux3D).' : ''}
        </div>
      </main>
    </div>
  );
}
